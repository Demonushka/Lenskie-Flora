List<TheoryLesson> theoryFor(String? role) {
  final key = switch (role) {
    'guide' => 'guide',
    'inspector' => 'inspector',
    _ => 'tourist',
  };
  return theoryLessons.where((lesson) => lesson.roles.contains(key)).toList();
}
